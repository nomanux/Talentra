// Regenerates src/styles/dark-icons.css: lists every single-colour (grey/black) SVG in src/assets
// so it can be inverted in dark mode. Run with `npm run gen:dark-icons` after adding assets.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, extname, join } from "node:path";

const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));

const toRgb = (c) => {
  if (c === "white") return [255, 255, 255];
  if (c === "black") return [0, 0, 0];
  let h = c.slice(1);
  if (h.length === 3) h = [...h].map((x) => x + x).join("");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};

// Mostly-dark glyphs with a small colour accent: invert + hue-rotate keeps the accent's hue.
const EXTRA = ["notification-01", "dots-three", "plus-phosphor"];
// Light grid backdrops: inverted, then blended so their opaque fill disappears into the dark card.
const BLEND = ["card-grid-bg", "card-grid-bg-employee"];

const mono = new Set(EXTRA);
for (const file of walk("src/assets").filter((f) => f.endsWith(".svg"))) {
  const svg = readFileSync(file, "utf8");
  const colours = [...svg.matchAll(/(?:fill|stroke|stop-color|flood-color)\s*[=:]\s*"?\s*(#[0-9a-fA-F]{3,6}|white|black)/g)].map((m) => toRgb(m[1]));
  if (!colours.length || (svg.includes("linearGradient") && svg.includes("url(#"))) continue;
  const grey = colours.every((c) => Math.max(...c) - Math.min(...c) < 24);
  const allWhite = colours.every((c) => Math.min(...c) >= 245);
  if (grey && !allWhite) mono.add(basename(file, extname(file)));
}

const selectors = [...mono].sort().flatMap((n) => [`.dark img[src*="/${n}."]`, `.dark img[src*="/${n}-"]`]);
writeFileSync(
  "src/styles/dark-icons.css",
  `/*
 * Single-colour (grey/black) icon assets are drawn for the light theme. In dark mode they are
 * inverted so they read as light-grey on the dark surfaces, matching the "Visual Design - Dark" page.
 * Multi-colour assets (logos, charts, flags, white-on-colour glyphs) are intentionally not listed.
 * Generated by scripts/gen-dark-icons.mjs from the SVG fill/stroke colours in src/assets.
 */
${selectors.join(",\n")} {
  filter: invert(1) hue-rotate(180deg);
}

${BLEND.flatMap((n) => [`.dark img[src*="/${n}."]`, `.dark img[src*="/${n}-"]`]).join(",\n")} {
  mix-blend-mode: lighten;
}
`,
);
console.log(`dark-icons.css: ${mono.size} icons`);
